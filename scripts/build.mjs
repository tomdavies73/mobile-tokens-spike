import { rm } from 'node:fs/promises';
import StyleDictionary from 'style-dictionary';

const identifier = /^[A-Za-z_][A-Za-z0-9_]*$/;
const hexColor = /^#([0-9a-fA-F]{6})$/;

function swiftToken(token) {
  const [layer, group, name] = token.path;
  const type = token.$type ?? token.type;
  const value = token.$value ?? token.value;
  if (token.path.length !== 3 || layer !== 'core' || !identifier.test(name)) {
    throw new Error(`Unsupported token path: ${token.path.join('.')}`);
  }

  if (group === 'color' && type === 'color') {
    const match = hexColor.exec(value);
    if (!match) throw new Error(`Expected #RRGGBB for ${token.path.join('.')}`);
    const channels = match[1].match(/../g).map((part) => parseInt(part, 16));
    return {
      group: 'Color',
      line: `        public static let ${name} = SwiftUI.Color(red: ${channels[0]}.0 / 255.0, green: ${channels[1]}.0 / 255.0, blue: ${channels[2]}.0 / 255.0)`,
    };
  }

  if (group === 'spacing' && type === 'number') {
    if (typeof value !== 'number' || !Number.isFinite(value) || value < 0) {
      throw new Error(`Expected a nonnegative number for ${token.path.join('.')}`);
    }
    return { group: 'Spacing', line: `        public static let ${name}: CGFloat = ${value}` };
  }

  throw new Error(`Unsupported token: ${token.path.join('.')} (${type})`);
}

StyleDictionary.registerFormat({
  name: 'swiftui/tokens',
  format: ({ dictionary }) => {
    const tokens = dictionary.allTokens.map(swiftToken);
    if (tokens.length === 0) throw new Error('No iOS tokens found');
    const lines = [
      '// Generated by Style Dictionary from data/tokens/core.json. Do not edit.',
      'import CoreGraphics',
      'import SwiftUI',
      '',
      'public enum DesignTokens {',
    ];
    for (const group of ['Color', 'Spacing']) {
      const members = tokens.filter((token) => token.group === group).map((token) => token.line).sort();
      if (members.length === 0) continue;
      lines.push(`    public enum ${group} {`, ...members, '    }', '');
    }
    lines.push('}', '');
    return lines.join('\n');
  },
});

function androidToken(token) {
  const [layer, group, name] = token.path;
  const type = token.$type ?? token.type;
  const value = token.$value ?? token.value;
  if (token.path.length !== 3 || layer !== 'core' || !identifier.test(name)) {
    throw new Error(`Unsupported token path: ${token.path.join('.')}`);
  }

  const resourceName = `dt_${layer}_${group}_${name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase()}`;
  if (group === 'color' && type === 'color' && hexColor.test(value)) {
    return { group, line: `    <color name="${resourceName}">${value.toUpperCase()}</color>` };
  }
  if (group === 'spacing' && type === 'number' && typeof value === 'number' && Number.isFinite(value) && value >= 0) {
    return { group, line: `    <dimen name="${resourceName}">${value}dp</dimen>` };
  }
  throw new Error(`Unsupported Android token: ${token.path.join('.')} (${type})`);
}

for (const group of ['color', 'spacing']) {
  StyleDictionary.registerFormat({
    name: `android/tokens-${group}`,
    format: ({ dictionary }) => {
      const lines = dictionary.allTokens.map(androidToken).filter((token) => token.group === group).map((token) => token.line).sort();
      if (lines.length === 0) throw new Error(`No Android ${group} tokens found`);
      return [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by Style Dictionary from data/tokens/core.json. Do not edit. -->',
        '<resources>',
        ...lines,
        '</resources>',
        '',
      ].join('\n');
    },
  });
}

await rm('dist', { recursive: true, force: true });
const dictionary = new StyleDictionary({
  source: ['data/tokens/**/*.json'],
  platforms: {
    ios: {
      buildPath: 'dist/ios/',
      files: [{ destination: 'DesignTokens.swift', format: 'swiftui/tokens' }],
    },
    css: {
      transformGroup: 'css',
      buildPath: 'dist/css/',
      files: [{ destination: 'tokens.css', format: 'css/variables' }],
    },
    android: {
      buildPath: 'dist/android/res/values/',
      files: [
        { destination: 'colors.xml', format: 'android/tokens-color' },
        { destination: 'dimens.xml', format: 'android/tokens-spacing' },
      ],
    },
  },
});
await dictionary.buildAllPlatforms();
